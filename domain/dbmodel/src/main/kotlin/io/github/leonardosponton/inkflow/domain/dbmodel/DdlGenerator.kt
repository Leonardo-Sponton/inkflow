package io.github.leonardosponton.inkflow.domain.dbmodel

import io.github.leonardosponton.inkflow.domain.canvas.scene.Scene

/**
 * Generates `CREATE TABLE` / `CREATE INDEX` statements from the tables on a tab. Tables are
 * ordered so referenced tables come first (cycles keep their drawing order); foreign keys are
 * declared inline, which all three dialects accept.
 */
class DdlGenerator(private val dialect: SqlDialect) {
    private data class Table(val id: String, val content: DbTableContent)

    fun generate(scene: Scene): String {
        val tables = DbValidators.tables(scene).map { Table(it.first.id.value, it.second) }
        return generate(tables.associate { it.id to it.content })
    }

    /** [tables] keyed by table node id. */
    fun generate(tables: Map<String, DbTableContent>): String {
        val ordered = order(tables)
        return buildString {
            append("-- Generated by Inkflow (").append(dialect.displayName).append(")\n")
            if (dialect == SqlDialect.SQLITE) append("PRAGMA foreign_keys = ON;\n")
            ordered.forEach { (_, t) ->
                append('\n')
                append(createTable(t, tables))
                append(indexes(t))
                append(comments(t))
            }
        }
    }

    private fun order(tables: Map<String, DbTableContent>): List<Pair<String, DbTableContent>> {
        val done = LinkedHashMap<String, DbTableContent>()
        val visiting = HashSet<String>()

        fun visit(id: String) {
            if (id in done || !visiting.add(id)) return
            val t = tables[id] ?: return
            t.columns.mapNotNull { it.references?.tableId }.filter { it != id }.forEach(::visit)
            done[id] = t
        }
        tables.keys.forEach(::visit)
        return done.toList()
    }

    private fun q(s: String) = dialect.quote(s)

    private fun createTable(t: DbTableContent, all: Map<String, DbTableContent>): String {
        val lines = mutableListOf<String>()
        val pk = t.primaryKey
        t.columns.forEach { c -> lines += "  " + columnDef(c, inlinePk = pk.size == 1) }
        if (pk.size > 1) lines += "  PRIMARY KEY (${pk.joinToString(", ") { q(it.name) }})"
        t.columns.forEach { c ->
            val ref = c.references ?: return@forEach
            val parent = all[ref.tableId] ?: return@forEach
            val parentCol = parent.column(ref.columnId) ?: return@forEach
            lines += "  FOREIGN KEY (${q(c.name)}) REFERENCES ${q(parent.name)} (${q(parentCol.name)})"
        }
        val tableComment = if (dialect == SqlDialect.MYSQL && t.comment.isNotBlank()) " COMMENT=${literal(t.comment)}" else ""
        return "CREATE TABLE ${q(t.name)} (\n" + lines.joinToString(",\n") + "\n)$tableComment;\n"
    }

    private fun columnDef(c: DbColumn, inlinePk: Boolean): String = buildString {
        append(q(c.name)).append(' ').append(dialect.type(c.type))
        if (c.primaryKey && inlinePk) append(" PRIMARY KEY")
        if (c.notNull && !(c.primaryKey && inlinePk)) append(" NOT NULL")
        if (c.unique && !c.primaryKey) append(" UNIQUE")
        if (c.defaultValue.isNotBlank()) append(" DEFAULT ").append(dialect.defaultValue(c.defaultValue, c.type))
        if (dialect == SqlDialect.MYSQL && c.comment.isNotBlank()) append(" COMMENT ").append(literal(c.comment))
    }

    private fun indexes(t: DbTableContent): String = buildString {
        t.indexes.forEach { idx ->
            val cols = idx.columnIds.mapNotNull { t.column(it)?.name }
            if (cols.isEmpty()) return@forEach
            append("CREATE ").append(if (idx.unique) "UNIQUE " else "").append("INDEX ").append(q(idx.name))
            append(" ON ").append(q(t.name)).append(" (").append(cols.joinToString(", ") { q(it) }).append(");\n")
        }
    }

    private fun comments(t: DbTableContent): String = when (dialect) {
        SqlDialect.POSTGRESQL -> buildString {
            if (t.comment.isNotBlank()) append("COMMENT ON TABLE ${q(t.name)} IS ${literal(t.comment)};\n")
            t.columns.filter { it.comment.isNotBlank() }.forEach {
                append("COMMENT ON COLUMN ${q(t.name)}.${q(it.name)} IS ${literal(it.comment)};\n")
            }
        }
        SqlDialect.SQLITE -> buildString {
            if (t.comment.isNotBlank()) append("-- ${t.name}: ${t.comment}\n")
            t.columns.filter { it.comment.isNotBlank() }.forEach { append("-- ${t.name}.${it.name}: ${it.comment}\n") }
        }
        SqlDialect.MYSQL -> ""
    }

    private fun literal(s: String) = "'" + s.replace("'", "''") + "'"
}
